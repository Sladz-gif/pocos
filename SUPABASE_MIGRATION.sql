-- POCOS Supabase Migration Script
-- Run this AFTER the initial SUPABASE_SETUP.sql to add new features
-- This adds support for Profiles, Bird Cages, Bird Count Records, and Notes

-- 1. PROFILES TABLE
-- Profiles allow managing different animal types (cattle, sheep, goat, horse, donkey, bird)
-- with custom fields specific to each profile type
CREATE TABLE IF NOT EXISTS profiles (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  ranch_id UUID REFERENCES ranch(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  animal_type TEXT NOT NULL CHECK (animal_type IN ('cattle', 'sheep', 'goat', 'horse', 'donkey', 'bird')),
  description TEXT,
  custom_fields JSONB DEFAULT '[]'::jsonb, -- Array of {id, label, fieldType, value}
  device_address TEXT CHECK (device_address ~ '^[a-f0-9]{16}$'), -- 16-character hex address for IoT devices (e.g., 989347d6c29e5e8b)
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. BIRD CAGES TABLE
-- Cages for bird profiles to track individual cage counts
CREATE TABLE IF NOT EXISTS bird_cages (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  profile_id UUID REFERENCES profiles(id) ON DELETE CASCADE,
  cage_id TEXT NOT NULL, -- Human readable cage identifier
  capacity INTEGER,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(profile_id, cage_id)
);

-- 3. BIRD COUNT RECORDS TABLE
-- Tracks bird counts over time for monitoring and history
CREATE TABLE IF NOT EXISTS bird_count_records (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  profile_id UUID REFERENCES profiles(id) ON DELETE CASCADE,
  cage_id UUID REFERENCES bird_cages(id) ON DELETE SET NULL,
  count INTEGER NOT NULL,
  timestamp TIMESTAMPTZ DEFAULT NOW(),
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. POULTRY REAL-TIME MONITORING
-- History table for 15-min logs
CREATE TABLE IF NOT EXISTS bird_counts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  timestamp TIMESTAMPTZ DEFAULT NOW(),
  total_birds INTEGER NOT NULL,
  interval_birds INTEGER NOT NULL,
  device_id TEXT NOT NULL
);

-- Live status table for real-time feed
CREATE TABLE IF NOT EXISTS poultry_live_status (
  id TEXT PRIMARY KEY, -- use 'current_status' as ID
  last_updated TIMESTAMPTZ DEFAULT NOW(),
  total_count INTEGER DEFAULT 0,
  is_active BOOLEAN DEFAULT true
);

